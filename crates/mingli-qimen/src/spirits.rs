//! 神盘：八神。
//!
//! 直符与值符同宫，其余七神阳顺阴逆布外八宫。第 5 / 6 位有两套并行称谓
//! （白虎 / 玄武 与 勾陈 / 朱雀），**两套都不分阴阳遁**，位序也完全一致，故两名并出。

use super::*;

/// 八神次序：值符 · 腾蛇 · 太阴 · 六合 · 白虎 · 玄武 · 九地 · 九天。
///
/// **位序不存在分歧**，这一点有结构上的硬约束：《烟波钓叟歌》「值符前三六合位，
/// 太阴之神在前二，后一宫中为九天，后二之神为九地」一句就把第 1 / 3 / 4 / 7 / 8 位钉死，
/// 第 2 位各家一致作腾蛇，歌诀唯独没有命名的正是第 5 / 6 位——所以分歧只可能落在称谓上。
///
/// 本表取《遁甲演义》「腾蛇、太阴、六合、白虎、玄武、九地、九天」，该书两遁通用此名。
/// 另一套称谓见 [`BA_SHEN_ALT`]。
pub const BA_SHEN: [&str; 8] =
    ["值符", "腾蛇", "太阴", "六合", "白虎", "玄武", "九地", "九天"];

/// 第 5 / 6 位的另一套称谓（勾陈 / 朱雀），其余六神同 [`BA_SHEN`]。
///
/// 出自《奇门遁甲统宗》「一值符、二腾蛇、三太阴、四六合、五勾陈、六朱雀、七九地、八九天」，
/// 该书同卷「八神类神」明言**异名同位**：「勾陈（下有白虎）：禀西方之金」「朱雀（下有玄武）：
/// 禀北方之水」——勾陈拿的是白虎的西方金、朱雀拿的是玄武的北方水，是同一位神的两个名字。
///
/// 这套称谓**同样不分阴阳遁**。坊间常说「阳遁称勾陈朱雀、阴遁称白虎玄武」，转盘语境下查不到
/// 站得住的依据：《奇门法窍》卷一记的恰好相反（「阳遁……白虎、元武；阴遁……朱雀、勾陈」），
/// 唯一直接这么说的现代来源自身前后矛盾。那条规则真正的出处是**飞盘九神**——
/// 它比转盘多一位「太常」凑成九神应九宫，与本表不是一回事。
pub const BA_SHEN_ALT: [&str; 8] =
    ["值符", "腾蛇", "太阴", "六合", "勾陈", "朱雀", "九地", "九天"];

/// 神盘八神。
#[derive(Debug, Clone, PartialEq, Eq)]
#[cfg_attr(feature = "serde", derive(serde::Serialize))]
pub struct SpiritPlate {
    /// 值符（直符）所在宫 1..=9 —— 八神的起点，随天盘值符走。
    pub start_palace: u8,
    /// 八神分布，`spirits[k]` = 第 `k+1` 宫；中 5 宫为空串（八神不入中宫）。
    pub spirits: [&'static str; 9],
    /// 同上，第 5 / 6 位改用另一套称谓（勾陈 / 朱雀）。两套位序相同、都不分阴阳遁，
    /// 只是名字不同——见 [`BA_SHEN_ALT`]。
    pub spirits_alt: [&'static str; 9],
}

/// 八神布列：直符与值符同宫，其余七神自值符宫起沿 [`ORBIT`] 阳遁顺时针、阴遁逆时针依次落宫。
///
/// 校验：起点坎 1 的阳遁盘 → 坎1值符 艮8腾蛇 震3太阴 巽4六合 离9白虎 坤2玄武 兑7九地 乾6九天，
/// 8 宫全中（公开教程例题）。
///
/// 起点取**天盘**旬首所在宫（即值符宫）；另有一路「地八神」以地盘旬首宫为起点，本 crate 不出。
#[must_use]
pub fn spirit_plate(zhi_fu_palace: u8, yang_dun: bool) -> SpiritPlate {
    let start_palace = lodged_palace(zhi_fu_palace);
    let start = orbit_index(start_palace);
    let mut spirits = [""; 9];
    let mut spirits_alt = [""; 9];
    for k in 0..8 {
        let i = if yang_dun { (start + k) % 8 } else { (start + 8 - k) % 8 };
        let p = ORBIT[i] as usize - 1;
        spirits[p] = BA_SHEN[k];
        spirits_alt[p] = BA_SHEN_ALT[k];
    }
    SpiritPlate { start_palace, spirits, spirits_alt }
}
