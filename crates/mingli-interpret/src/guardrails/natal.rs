/// 确定性等级的中文标记。
pub(crate) fn det_mark(s: Determinism) -> &'static str {
    match s {
        Determinism::Det => "DET 确定",
        Determinism::Sto => "STO 随机·可复现",
        Determinism::Und => "UND 欠定🟡",
    }
}

